"""Run the pinned slicer offline; validate and summarize its actual toolpaths."""
import asyncio
import hashlib
import json
import math
import os
import re
import random
from pathlib import Path

async def command(*args, timeout=30):
    process = await asyncio.create_subprocess_exec(*args, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    try:
        out, err = await asyncio.wait_for(process.communicate(), timeout)
        return process.returncode, out, err
    finally:
        if process.returncode is None:
            process.kill()
            await process.wait()

IMAGE = 'ada-jarvis-slicer:2.9.2'
PROFILE = Path(__file__).parent / 'profiles/k2-0.4.ini'

def profile_revision():
    return hashlib.sha256(PROFILE.read_bytes() + (PROFILE.parent/'k2-cfs-start.gcode').read_bytes() + IMAGE.encode()).hexdigest()


def profile_text(request):
    text = PROFILE.read_text()
    values = {'layer_height': {'standard': .2, 'draft': .28, 'fine': .12}[request['quality']],
              'fill_density': f"{request['infill']}%", 'support_material': int(request['supports'] != 'off'),
              'support_material_threshold': request.get('support_angle', 45), 'perimeters': 5,
              'brim_width': 5 if request['brim'] else 0}
    if request['material'] == 'PETG':
        values.update(temperature=240, first_layer_temperature=240, bed_temperature=80,
                      first_layer_bed_temperature=80, filament_density=1.27, filament_type='PETG',
                      min_fan_speed=30, max_fan_speed=50, filament_max_volumetric_speed=8)
    for key, value in values.items():
        text = re.sub(r'^' + re.escape(key) + r' = .*$', f'{key} = {value}', text, flags=re.M)
    text += '\nsupport_material_buildplate_only = ' + str(int(request['supports'] == 'buildplate'))
    text += '\nsupport_material_style = snug\n'
    if request.get('source') == 'cfs':
        start = (PROFILE.parent / 'k2-cfs-start.gcode').read_text()
        start = '\\n'.join(line for line in start.splitlines() if not line.startswith(';'))
        text = re.sub(r'^start_gcode = .*$', lambda _: 'start_gcode = ' + start, text, flags=re.M)
    return text


def inspect_gcode(path):
    position = [0., 0., 0.]; absolute = True; relative_e = False; epos = 0.
    layer = None; layers = []; segment_count = 0; model_started = False; role = 0
    bounds = [[math.inf] * 3, [-math.inf] * 3]; extrusion_moves = 0
    estimate = None; grams = None; version = ''; saw_start = saw_end = False
    layer_moves = 0; sampler = random.Random(0)
    with path.open() as source:
        for line in source:
            if 'generated by PrusaSlicer' in line:
                version = line.strip('; \n')
            if line.startswith('; estimated printing time (normal mode) = '):
                estimate = line.split(' = ', 1)[1].strip()
            if line.startswith('; filament used [g] = '):
                grams = float(line.split(' = ', 1)[1].split(',')[0])
            if line.startswith(';LAYER_CHANGE'):
                model_started = True
                layer_moves = 0
                layer = {'z': None, 'segments': []}; layers.append(layer)
            if line.startswith(';TYPE:'):
                kind = line.split(':', 1)[1].lower()
                role = 1 if 'support' in kind else 2 if 'skirt' in kind or 'brim' in kind else 0
            code = line.split(';', 1)[0].strip()
            if not code:
                continue
            op = code.split()[0]
            if model_started and op in ('G2', 'G3'):
                raise ValueError('Unexpected arc toolpath. Disable arc fitting and slice again.')
            if op == 'START_PRINT': saw_start = True
            if op == 'END_PRINT': saw_end = True
            if op == 'G90': absolute = True
            if op == 'G91': absolute = False
            if op == 'M82': relative_e = False
            if op == 'M83': relative_e = True
            if op not in ('G0', 'G1', 'G92'):
                continue
            values = {k:float(v) for k,v in re.findall(r'([XYZE])([-+]?\d*\.?\d+)', code)}
            if not all(math.isfinite(v) for v in values.values()):
                raise ValueError('Slicer produced invalid coordinates.')
            old = position.copy()
            for i, axis in enumerate('XYZ'):
                if axis in values:
                    position[i] = values[axis] if absolute or op == 'G92' else position[i] + values[axis]
            amount = values.get('E', 0) if relative_e else values.get('E', epos) - epos
            if 'E' in values: epos = values['E']
            if op == 'G92':
                continue
            limits = [(0,260), (0,260), (0,260)] if model_started else [(-12,262),(-3,296.5),(-.01,270)]
            # A first-layer Z move may still be at the firmware's purge location.
            # Check each commanded axis; deposited paths below must be inside the bed.
            if any((p < lo-.01 or p > hi+.01) and axis in values
                   for axis,p,(lo,hi) in zip('XYZ',position,limits)):
                raise ValueError('Toolpath exceeds the K2 build volume. Change orientation or reduce the design.')
            if model_started and amount > 0 and old[:2] != position[:2]:
                if min(*old[:2], *position[:2]) < 11.99 or max(*old[:2], *position[:2]) > 248.01:
                    raise ValueError('Model, skirt, brim, or supports exceed the reserved print area (12–248 mm). Reduce the model or brim.')
                extrusion_moves += 1
                for i, p in enumerate(position):
                    bounds[0][i] = min(bounds[0][i], p); bounds[1][i] = max(bounds[1][i], p)
                if layer is not None:
                    layer['z'] = round(position[2], 3)
                    # Sample across the entire layer, so dense early paths cannot
                    # hide parts or supports printed later on the same layer.
                    layer_moves += 1
                    segment = [round(x, 2) for x in [*old[:2], *position[:2]]] + [role]
                    if len(layer['segments']) < 6000:
                        layer['segments'].append(segment)
                        segment_count += 1
                    else:
                        index = sampler.randrange(layer_moves)
                        if index < 6000:
                            layer['segments'][index] = segment
    if not saw_start or not saw_end or not version or not extrusion_moves:
        raise ValueError('Slicer output is missing a start/end macro or printable toolpaths.')
    return {'estimate': estimate, 'filament_g': grams, 'slicer': version, 'layer_count': len(layers),
            'bounds': bounds, 'extrusion_moves': extrusion_moves,
            'preview_truncated': segment_count < extrusion_moves, 'layers': layers}


class Slicer:
    async def available(self):
        try:
            code, _, _ = await command('docker', 'image', 'inspect', IMAGE)
            return code == 0
        except (OSError, TimeoutError):
            return False

    async def slice(self, folder, request):
        if not await self.available():
            raise ValueError('Printing worker unavailable. Run bash scripts/setup_printing.sh.')
        folder = folder.resolve(); output = folder / 'output'; output.mkdir(exist_ok=True)
        (folder / 'profile.ini').write_text(profile_text(request))
        name = 'jarvis-slice-' + folder.name
        args = ['docker', 'run', '--rm', '--name', name, '--network', 'none', '--read-only',
                '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges',
                '--user', f'{os.getuid()}:{os.getgid()}', '--cpus', '2', '--memory', '2g',
                '--memory-swap', '2g', '--pids-limit', '128', '--ulimit', 'fsize=67108864:67108864',
                '--tmpfs', '/tmp:rw,nosuid,size=128m,mode=1777', '--log-driver', 'none',
                '--mount', f'type=bind,src={folder},dst=/input,readonly',
                '--mount', f'type=bind,src={output},dst=/output', IMAGE,
                '--load', '/input/profile.ini', '--threads', '2', '--dont-arrange',
                '--export-gcode', '--output', '/output/print.gcode', '/input/model.stl']
        try:
            code, stdout, stderr = await command(*args, timeout=240)
            (folder / 'slicer.log').write_bytes((stdout + stderr)[-32000:])
            if code:
                raise ValueError('Slicing failed. Check the job’s slicer.log and choose a simpler model or different orientation.')
        except TimeoutError:
            raise ValueError('Slicing exceeded four minutes. Simplify the model and retry.') from None
        finally:
            await command('docker', 'rm', '-f', name)
        path = output / 'print.gcode'
        if path.is_symlink() or not path.is_file() or not 0 < path.stat().st_size <= 64 * 1024 * 1024:
            raise ValueError('Slicer did not produce a valid print file.')
        metadata = await asyncio.to_thread(inspect_gcode, path)
        preview = {'layers': metadata.pop('layers'), 'truncated': metadata['preview_truncated']}
        (output / 'preview.json').write_text(json.dumps(preview, separators=(',', ':')))
        metadata['sha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
        metadata['profile_sha256'] = hashlib.sha256((folder / 'profile.ini').read_bytes()).hexdigest()
        metadata['profile_revision'] = profile_revision()
        return metadata
